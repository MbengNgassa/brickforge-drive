export const PARTS_MAP: Record<BrickPartId, BrickPartDef> = PARTS.reduce(
  (acc, part) => {
    acc[part.id] = part;
    return acc;
  },
  {} as Record<BrickPartId, BrickPartDef>
);

export function getRotatedDims(part: BrickPartDef, rot: 0 | 1 | 2 | 3): { w: number; h: number; d: number } {
  if (rot % 2 === 1) {
    return { w: part.d, h: part.h, d: part.w };
  }
  return { w: part.w, h: part.h, d: part.d };
}

export function getBrickCenterWorld(brick: PlacedBrick): { x: number; y: number; z: number } {
  const part = PARTS_MAP[brick.partId];
  const dims = getRotatedDims(part, brick.rot);
  return {
    x: (brick.gx + dims.w / 2) * STUD_SIZE,
    y: (brick.gy + dims.h / 2) * PLATE_HEIGHT,
    z: (brick.gz + dims.d / 2) * STUD_SIZE,
  };
}

export function getOccupiedKeys(brick: PlacedBrick): string[] {
  const part = PARTS_MAP[brick.partId];
  const dims = getRotatedDims(part, brick.rot);
  const keys: string[] = [];
  for (let x = 0; x < dims.w; x++) {
    for (let y = 0; y < dims.h; y++) {
      for (let z = 0; z < dims.d; z++) {
        keys.push(`${brick.gx + x},${brick.gy + y},${brick.gz + z}`);
      }
    }
  }
  return keys;
}

export function calculateVehicleStats(bricks: PlacedBrick[]): VehicleStats {
  let mass = 0;
  let wheelCount = 0;
  let thrusterCount = 0;
  let springCount = 0;
  let topSpeedRaw = 42;
  let boostRaw = 28;
  let gripRaw = 38;
  let ramRaw = 16;
  let armorRaw = 22;
  let totalBrickHp = 0;

  for (const b of bricks) {
    const p = PARTS_MAP[b.partId];
    if (!p) continue;
    mass += p.mass;
    totalBrickHp += p.hp;
    if (p.isWheel) wheelCount++;
    if (p.isThruster) thrusterCount++;
    if (p.isSpring) springCount++;
    topSpeedRaw += p.topSpeedBonus;
    boostRaw += p.boostBonus;
    gripRaw += p.gripBonus;
    ramRaw += p.ramBonus;
    armorRaw += p.armorBonus;
  }

  const effectiveMass = Math.max(8, mass);
  const weightPenalty = Math.max(0, (effectiveMass - 38) * 0.28);
  const wheelFactor = wheelCount >= 4 ? 1.0 : wheelCount >= 2 ? 0.85 : 0.62;

  const topSpeed = Math.round(Math.min(100, Math.max(25, (topSpeedRaw - weightPenalty * 0.55) * wheelFactor)));
  const acceleration = Math.round(
    Math.min(100, Math.max(28, (50 + thrusterCount * 12 + Math.min(wheelCount, 6) * 4 - weightPenalty * 0.7) * wheelFactor))
  );
  const handling = Math.round(
    Math.min(100, Math.max(28, (gripRaw - weightPenalty * 0.35) * (wheelCount >= 4 ? 1.0 : 0.78)))
  );
  const armor = Math.round(Math.min(100, Math.max(20, armorRaw * 0.85 + effectiveMass * 0.55)));
  const ramPower = Math.round(Math.min(100, Math.max(20, ramRaw * 1.35 + effectiveMass * 0.65)));

  return {
    brickCount: bricks.length,
    maxBricks: MAX_BRICKS,
    mass: Math.round(effectiveMass * 10) / 10,
    wheelCount,
    thrusterCount,
    springCount,
    topSpeed,
    acceleration,
    handling,
    armor,
    ramPower,
    // Punchy, controllable arcade speeds (easy to aim rams & carve tight corners!)
    physMaxSpeed: 28 + (topSpeed / 100) * 18, // 28..46 units/sec (100..165 km/h)
    physAccel: 22 + (acceleration / 100) * 18,
    physTurnRate: 2.05 + (handling / 100) * 1.15,
    physGrip: 6.4 + (handling / 100) * 6.5,
    // Tougher chassis HP so Derby battles last 10-14 exciting clashes instead of 3 hits!
    physMaxHp: Math.max(420, Math.round(320 + totalBrickHp * 0.85 + armor * 4.5)),
    physRamMultiplier: 0.88 + (ramPower / 100) * 1.1,
    physBoostPower: 11 + Math.min(boostRaw, 100) * 0.12, // +11..+23 crisp nitro burst
    // Snappy controlled hops (with g=42, lands cleanly in ~0.55–1.1s!)
    physJumpImpulse: 11.5 + Math.min(springCount, 4) * 2.8,
  };
}
